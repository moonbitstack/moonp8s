"""Write src/metric/native_bounds.mbt from client_golang's `nativeHistogramBounds`.

    python scripts/native/gen_bounds.py <path to client_golang's prometheus/histogram.go>

The table is the fraction at which each bucket of a positive schema starts, 2^(i/2^schema) / 2,
as client_golang and Prometheus carry it. It is copied rather than computed so that a bucket
boundary is the same float64 on both sides: a value that lands exactly on one goes to the same
bucket here as there. `scripts/native/compare` checks the result against client_golang itself.
"""
import pathlib
import re
import sys

source = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8")
start = source.index("var nativeHistogramBounds = [][]float64{")
end = source.index("\n}\n", start)
body = source[start:end]
rows = []
for chunk in re.split(r"// Schema [^\n]*\n", body)[1:]:
    rows.append(re.findall(r"\d+\.\d+(?:e-?\d+)?", chunk))
assert [len(r) for r in rows] == [1 << s for s in range(9)], [len(r) for r in rows]

out = pathlib.Path(__file__).resolve().parents[2] / "src/metric/native_bounds.mbt"
lines = [
    "// Code generated by scripts/native/gen_bounds.py from client_golang's nativeHistogramBounds. DO NOT EDIT.",
    "",
    "///|",
    "// Where each bucket of a positive schema starts, as the fraction `frexp` gives: index",
    "// `schema`, then the `2^schema` fractions in ascending order.",
    "let native_bounds : FixedArray[FixedArray[Double]] = [",
]
for row in rows:
    lines.append("  [")
    for i in range(0, len(row), 4):
        lines.append("    " + ", ".join(row[i : i + 4]) + ",")
    lines.append("  ],")
lines.append("]")
out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
print(f"{out}: {sum(len(r) for r in rows)} bounds over {len(rows)} schemas")
