"""Write src/expo/native_vectors_wbtest.mbt from client_golang's native histogram vectors.

    (cd scripts/native/compare && go mod tidy && go run .) > /tmp/vectors.json
    python scripts/native/gen_vectors.py /tmp/vectors.json

Every double is carried as its bits, so a value on a bucket boundary arrives as exactly that
value. The test replays each scenario's observations through moonp8s and compares the Histogram
message it writes with the one client_golang wrote, byte for byte.
"""
import json
import pathlib
import struct
import sys

vectors = json.loads(pathlib.Path(sys.argv[1]).read_text(encoding="utf-8"))
out = pathlib.Path(__file__).resolve().parents[2] / "src/expo/native_vectors_wbtest.mbt"


def bits(x):
    return "0x%016xUL" % struct.unpack("<Q", struct.pack("<d", x))[0]


def double(x):
    return bits(x) + ".reinterpret_as_double()"


lines = [
    "// Code generated by scripts/native/gen_vectors.py from client_golang's output. DO NOT EDIT.",
    "",
    "///|",
    "priv struct Vector {",
    "  name : String",
    "  factor : Double",
    "  zero_threshold : Double",
    "  max_buckets : Int32",
    "  max_zero_threshold : Double",
    "  buckets : Array[Double]?",
    "  values : Array[UInt64]",
    "  message : String",
    "}",
]
for i, v in enumerate(vectors):
    buckets = "None" if v["buckets"] is None else "Some([" + ", ".join(double(b) for b in v["buckets"]) + "])"
    lines += ["", "///|", f"fn vector_{i}() -> Vector {{", "  {",
              f"    name: {json.dumps(v['name'])},",
              f"    factor: {double(v['factor'])},",
              f"    zero_threshold: {double(v['zero_threshold'])},",
              f"    max_buckets: {v['max_buckets']},",
              f"    max_zero_threshold: {double(v['max_zero_threshold'])},",
              f"    buckets: {buckets},",
              "    values: ["]
    values = v["values"] or []
    for j in range(0, len(values), 3):
        lines.append("      " + " ".join(f"0x{b}UL," for b in values[j : j + 3]))
    lines += ["    ],", f"    message: \"{v['message']}\",", "  }", "}"]
lines += ["", "///|", "fn vectors() -> Array[Vector] {",
          "  [" + ", ".join(f"vector_{i}()" for i in range(len(vectors))) + "]", "}"]
out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
print(f"{out}: {len(vectors)} scenarios, {sum(len(v['values'] or []) for v in vectors)} observations")
