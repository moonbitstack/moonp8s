#!/usr/bin/env python3
"""Generate the golden exposition vectors from the official Python client.

Usage: gen_golden.py --client-python /path/to/prometheus/client_python

The generated src/expo/golden.mbt is committed; CI replays it instead of
running Python. Re-run this when the reference client's output changes.
"""

import argparse
import os
import sys


def moonbit_literal(text):
    out = (text.replace('\\', '\\\\').replace('"', '\\"')
               .replace('\n', '\\n').replace('\r', '\\r'))
    return '"' + out + '"'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--client-python', required=True)
    parser.add_argument('--output', default='src/expo/golden_vectors_wbtest.mbt')
    args = parser.parse_args()

    sys.path.insert(0, os.path.abspath(args.client_python))
    import prometheus_client.metrics as metrics_module
    metrics_module.time.time = lambda: 1700000000.0
    from prometheus_client import (CollectorRegistry, Counter, Gauge, Histogram,
                                   Summary, Info, Enum, exposition)
    from prometheus_client.openmetrics import exposition as openmetrics

    registry = CollectorRegistry()
    requests = Counter('http_requests', 'HTTP requests.', ['method', 'code'],
                       registry=registry)
    requests.labels('GET', '200').inc()
    requests.labels('POST', '500').inc(2.5)
    temperature = Gauge('temperature_celsius', 'Temperature.', registry=registry)
    temperature.set(21.5)
    latency = Histogram('request_latency_seconds', 'Latency.', ['route'],
                        registry=registry)
    for value in (0.05, 0.3, 2.0):
        latency.labels('/').observe(value)
    size = Summary('request_size_bytes', 'Size.', registry=registry)
    size.observe(512)
    size.observe(1024)
    build = Info('build_info', 'Build info.', registry=registry)
    build.info({'version': '1.2.3', 'commit': 'abc'})
    state = Enum('task_state', 'Task state.',
                 states=['starting', 'running', 'stopped'], registry=registry)
    state.state('running')

    text = exposition.generate_latest(registry).decode('utf-8')
    om = openmetrics.generate_latest(registry).decode('utf-8')

    lines = [
        '// Copyright 2026 Leo Cheng',
        '// SPDX-License-Identifier: Apache-2.0',
        '',
        '// Generated by scripts/gen_golden.py from prometheus/client_python.',
        '// Do not edit by hand.',
        '',
        '///|',
        '/// The compatibility-format exposition the reference client produced for',
        '/// the registry built in `golden_families`.',
        f'let golden_text : String = {moonbit_literal(text)}',
        '',
        '///|',
        '/// The OpenMetrics exposition the reference client produced for the same',
        '/// registry.',
        f'let golden_openmetrics : String = {moonbit_literal(om)}',
        '',
    ]
    with open(args.output, 'w', encoding='utf-8', newline='\n') as handle:
        handle.write('\n'.join(lines))
    print(f'wrote {args.output}')


if __name__ == '__main__':
    main()
